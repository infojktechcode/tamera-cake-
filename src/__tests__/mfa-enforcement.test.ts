import { describe, it, expect, vi, beforeEach, afterEach } from "vitest";

// Mock environment
const originalEnv = process.env;

describe("MFA Enforcement - enforceAal2ForSuperadmin", () => {
  beforeEach(() => {
    vi.resetModules();
    process.env = { ...originalEnv };
  });

  afterEach(() => {
    process.env = originalEnv;
  });

  // Helper to create a mock Supabase client
  const createMockSupabase = (aal: string) => ({
    auth: {
      getUser: vi.fn().mockResolvedValue({
        data: {
          user: {
            id: "user-1",
            email: "superadmin@test.com",
            app_metadata: { aal },
            user_metadata: {},
          },
        },
      }),
    },
  });

  it("throws MFA_REQUIRED for superadmin at AAL1 when enforcement enabled", async () => {
    process.env.NEXT_PUBLIC_ENFORCE_MFA = "true";

    const { enforceAal2ForSuperadmin } = await import("@/lib/session");
    const mockSupabase = createMockSupabase("aal1");

    await expect(enforceAal2ForSuperadmin(mockSupabase, "superadmin")).rejects.toThrow(
      "MFA_REQUIRED"
    );
  });

  it("does NOT throw for superadmin at AAL2 when enforcement enabled", async () => {
    process.env.NEXT_PUBLIC_ENFORCE_MFA = "true";

    const { enforceAal2ForSuperadmin } = await import("@/lib/session");
    const mockSupabase = createMockSupabase("aal2");

    await expect(enforceAal2ForSuperadmin(mockSupabase, "superadmin")).resolves.toBeUndefined();
  });

  it("does NOT throw for manager at AAL1 (unaffected by AAL2 enforcement)", async () => {
    process.env.NEXT_PUBLIC_ENFORCE_MFA = "true";

    const { enforceAal2ForSuperadmin } = await import("@/lib/session");
    const mockSupabase = createMockSupabase("aal1");

    await expect(enforceAal2ForSuperadmin(mockSupabase, "manager")).resolves.toBeUndefined();
  });

  it("does NOT throw for superadmin at AAL1 when enforcement disabled", async () => {
    process.env.NEXT_PUBLIC_ENFORCE_MFA = "false";

    const { enforceAal2ForSuperadmin } = await import("@/lib/session");
    const mockSupabase = createMockSupabase("aal1");

    await expect(enforceAal2ForSuperadmin(mockSupabase, "superadmin")).resolves.toBeUndefined();
  });

  it("does NOT throw for superadmin at AAL1 when enforcement unset", async () => {
    delete process.env.NEXT_PUBLIC_ENFORCE_MFA;

    const { enforceAal2ForSuperadmin } = await import("@/lib/session");
    const mockSupabase = createMockSupabase("aal1");

    await expect(enforceAal2ForSuperadmin(mockSupabase, "superadmin")).resolves.toBeUndefined();
  });
});

